const STOP = new Set(['the','and','for','that','with','this','from','were','have','has','are','was','into','their','there','which','these','those','been','being','also','than','then','when','where','while','using','used','such','not','but','can','may','might','could','would','should','our','its','they','them','study','research']);

export function assessWriting(text) {
  const words = text.trim().split(/\s+/).filter(Boolean);
  const sentences = text.split(/[.!?]+/).map(s => s.trim()).filter(Boolean);
  const longSentences = sentences.filter(s => s.split(/\s+/).length > 35).length;
  const repeatedOpeners = {};
  for (const sentence of sentences) {
    const first = sentence.toLowerCase().split(/\s+/).slice(0, 2).join(' ');
    if (first) repeatedOpeners[first] = (repeatedOpeners[first] || 0) + 1;
  }
  const repeated = Object.entries(repeatedOpeners).filter(([, n]) => n >= 3).map(([phrase, count]) => ({ phrase, count }));
  const observations = [];
  if (longSentences) observations.push({ level: 'review', title: 'Long sentences', detail: `${longSentences} sentence(s) exceed 35 words. Review whether they can be made clearer.` });
  if (repeated.length) observations.push({ level: 'review', title: 'Repeated sentence openings', detail: 'Some sentence openings recur several times; vary them only where it improves clarity.', items: repeated });
  if (words.length < 80) observations.push({ level: 'info', title: 'Short sample', detail: 'This sample is too short for meaningful style-pattern interpretation.' });
  observations.push({ level: 'info', title: 'Authorship limitation', detail: 'These are writing-quality heuristics. They cannot determine whether text was written by a human or AI.' });
  return {
    wordCount: words.length,
    sentenceCount: sentences.length,
    averageWordsPerSentence: sentences.length ? Math.round(words.length / sentences.length * 10) / 10 : 0,
    observations,
    verdict: 'No authorship verdict generated'
  };
}

/**
 * AI-Generated Text Detection & Authorship Heuristics Engine
 * Provides advisory, probabilistic indicators with prominent uncertainty disclosures.
 */
export function assessAiAuthorship(text = '') {
  const normalized = text.trim();
  const words = normalized.split(/\s+/).filter(Boolean);
  const totalWords = words.length;

  if (totalWords === 0) {
    return {
      wordCount: 0,
      sentenceCount: 0,
      averageWordsPerSentence: 0,
      aiLikelihood: 0,
      humanLikelihood: 100,
      confidence: 'low',
      uncertaintyBand: '± 20%',
      classification: 'insufficient_text',
      burstinessScore: 0,
      burstinessEvaluation: 'Insufficient sample',
      perplexityEstimate: 'Insufficient sample',
      indicators: [],
      flaggedSegments: [],
      advisoryNotice: 'ADVISORY ONLY: Statistical indicators cannot definitively prove human vs. AI authorship. Text generated by non-native English speakers or highly structured academic writing can produce false positives. Never use this score as sole proof of academic misconduct.',
      limitations: 'Analysis is heuristic-based, examining sentence length variance (burstiness), vocabulary distribution, and formulaic AI transition patterns. No external commercial detector database is queried.'
    };
  }

  // 1. Sentence length variance (Burstiness)
  const sentences = normalized.match(/[^.!?]+[.!?]+/g) || [normalized];
  const sentenceWordCounts = sentences.map(s => s.trim().split(/\s+/).filter(Boolean).length).filter(c => c > 0);
  const sentenceCount = sentenceWordCounts.length || 1;
  const avgSentenceLength = Math.round((totalWords / sentenceCount) * 10) / 10;

  // Standard deviation calculation
  const variance = sentenceWordCounts.reduce((acc, len) => acc + Math.pow(len - avgSentenceLength, 2), 0) / sentenceCount;
  const stdDev = Math.round(Math.sqrt(variance) * 10) / 10;

  let burstinessCategory = 'Moderate variance';
  let burstinessFactor = 0.5;
  if (stdDev < 4.5 && sentenceCount >= 4) {
    burstinessCategory = 'Low variance (Uniform cadence, common in LLMs)';
    burstinessFactor = 0.8;
  } else if (stdDev > 8.0) {
    burstinessCategory = 'High variance (Dynamic rhythm, typical of human prose)';
    burstinessFactor = 0.2;
  }

  // 2. Formulaic AI Clichés and Transition Patterns
  const AI_PATTERNS = [
    { pattern: /\bdelve(?:s|d)?\s+into\b/gi, label: '"delve into"', weight: 4 },
    { pattern: /\ba\s+testament\s+to\b/gi, label: '"a testament to"', weight: 4 },
    { pattern: /\btapestry\s+of\b/gi, label: '"tapestry of"', weight: 5 },
    { pattern: /\bbeacon\s+of\b/gi, label: '"beacon of"', weight: 4 },
    { pattern: /\bpivotal\s+role\b/gi, label: '"pivotal role"', weight: 3 },
    { pattern: /\bcrucial\s+aspect\b/gi, label: '"crucial aspect"', weight: 2 },
    { pattern: /\bin\s+conclusion,\s+(?:it\s+is\s+evident|it\s+is\s+important)\b/gi, label: '"formulaic conclusion"', weight: 4 },
    { pattern: /\bit\s+is\s+worth\s+noting\s+that\b/gi, label: '"it is worth noting that"', weight: 3 },
    { pattern: /\bever-evolving\s+landscape\b/gi, label: '"ever-evolving landscape"', weight: 5 },
    { pattern: /\bseamlessly\s+integrate(?:s|d)?\b/gi, label: '"seamlessly integrate"', weight: 3 },
    { pattern: /\bvital\s+importance\b/gi, label: '"vital importance"', weight: 2 },
    { pattern: /\bharness(?:ing)?\s+the\s+power\s+of\b/gi, label: '"harnessing the power of"', weight: 4 }
  ];

  const flaggedSegments = [];
  let aiMarkerScore = 0;
  for (const { pattern, label, weight } of AI_PATTERNS) {
    const matches = normalized.match(pattern);
    if (matches && matches.length > 0) {
      aiMarkerScore += matches.length * weight;
      flaggedSegments.push({
        type: 'formulaic_marker',
        label,
        occurrences: matches.length,
        note: `Frequent hallmark of generative AI templates: ${label}`
      });
    }
  }

  // 3. Repeated Sentence Openers Check
  const openers = {};
  for (const s of sentences) {
    const tokens = s.trim().split(/\s+/).slice(0, 2).map(w => w.toLowerCase());
    if (tokens.length >= 2) {
      const opener = tokens.join(' ');
      openers[opener] = (openers[opener] || 0) + 1;
    }
  }
  const repetitiveOpeners = Object.entries(openers).filter(([, count]) => count >= 3);
  if (repetitiveOpeners.length > 0) {
    repetitiveOpeners.forEach(([phrase, count]) => {
      flaggedSegments.push({
        type: 'structural_uniformity',
        label: `Repeated sentence start: "${phrase}" (${count}x)`,
        occurrences: count,
        note: 'Monotonous sentence opener structure across consecutive clauses.'
      });
    });
  }

  // 4. Lexical diversity
  const uniqueTokens = new Set(words.map(w => w.toLowerCase().replace(/[^a-z0-9]/g, '')));
  const ttr = Math.round((uniqueTokens.size / totalWords) * 100);

  // 5. Aggregate probabilistic estimate
  let rawScore = 15;
  if (burstinessFactor > 0.6) rawScore += 25;
  else if (burstinessFactor < 0.3) rawScore -= 8;

  rawScore += Math.min(45, aiMarkerScore * 3.5);
  if (repetitiveOpeners.length > 0) rawScore += Math.min(15, repetitiveOpeners.length * 4);
  if (totalWords < 20) rawScore = Math.min(rawScore, 30);

  const aiLikelihood = Math.max(5, Math.min(95, Math.round(rawScore)));
  const humanLikelihood = 100 - aiLikelihood;

  let classification = 'likely_human';
  if (aiLikelihood > 65) classification = 'likely_ai_generated';
  else if (aiLikelihood >= 35) classification = 'mixed_or_uncertain';

  const indicators = [
    {
      name: 'Sentence Burstiness',
      value: `${stdDev} σ`,
      interpretation: burstinessCategory,
      status: stdDev >= 7.5 ? 'normal' : (stdDev <= 4.5 ? 'review' : 'moderate')
    },
    {
      name: 'Vocabulary Predictability',
      value: `${ttr}% unique words`,
      interpretation: ttr > 55 ? 'Rich diverse vocabulary' : (ttr < 35 ? 'Repetitive / uniform tokens' : 'Moderate lexical breadth'),
      status: ttr >= 45 ? 'normal' : 'review'
    },
    {
      name: 'AI Transition Clichés',
      value: `${flaggedSegments.filter(f => f.type === 'formulaic_marker').length} detected`,
      interpretation: aiMarkerScore > 8 ? 'Elevated presence of LLM transition idioms' : 'Natural academic phrasing',
      status: aiMarkerScore > 8 ? 'review' : 'normal'
    }
  ];

  return {
    wordCount: totalWords,
    sentenceCount,
    averageWordsPerSentence: avgSentenceLength,
    aiLikelihood,
    humanLikelihood,
    confidence: totalWords > 120 ? 'moderate' : 'low',
    uncertaintyBand: '± 20%',
    classification,
    burstinessScore: stdDev,
    burstinessEvaluation: burstinessCategory,
    perplexityEstimate: ttr > 50 ? 'High lexical variety' : 'Moderate to uniform',
    indicators,
    flaggedSegments,
    advisoryNotice: 'ADVISORY ONLY: Statistical indicators cannot definitively prove human vs. AI authorship. Text generated by non-native English speakers or highly structured academic writing can produce false positives. Never use this score as sole proof of academic misconduct.',
    limitations: 'Analysis is heuristic-based, examining sentence length variance (burstiness), vocabulary distribution, and formulaic AI transition patterns. No external commercial detector database is queried.'
  };
}

/**
 * Plagiarism & Document Similarity Assessment Engine
 * Supports quotation and references exclusion with Crossref source linkage.
 */
export function assessPlagiarismAndSimilarity(text = '', options = {}) {
  const {
    excludeQuotes = true,
    excludeReferences = true,
    excludeSmallPhrases = false,
    minPhraseWords = 5
  } = options;
  const rawText = text.trim();
  let workingText = rawText;
  let quotationsCount = 0;
  let referencesExcluded = false;
  let excludedWordsCount = 0;

  // 1. Identify and optionally exclude quotations ("..." or “...”)
  const quoteRegex = /(["“][^"”]{15,}["”]|`[^`]{15,}`)/g;
  const quotesFound = rawText.match(quoteRegex) || [];
  quotationsCount = quotesFound.length;

  if (excludeQuotes && quotesFound.length > 0) {
    quotesFound.forEach(q => {
      const qWords = q.split(/\s+/).filter(Boolean).length;
      excludedWordsCount += qWords;
    });
    workingText = workingText.replace(quoteRegex, ' [EXCLUDED_QUOTE] ');
  }

  // 2. Identify and optionally exclude References / Bibliography section
  const refHeadingRegex = /(?:\n|^)(?:#{1,3}\s+)?(?:References|Bibliography|Works Cited|Literature Cited)\s*(?:\n|$)/i;
  const refMatch = workingText.search(refHeadingRegex);
  if (refMatch !== -1) {
    referencesExcluded = true;
    if (excludeReferences) {
      const refSection = workingText.slice(refMatch);
      const refWords = refSection.split(/\s+/).filter(Boolean).length;
      excludedWordsCount += refWords;
      workingText = workingText.slice(0, refMatch);
    }
  }

  // 3. Compute text word metrics
  const analyzedWords = workingText.split(/\s+/).filter(w => w && w !== '[EXCLUDED_QUOTE]');
  const totalAnalyzed = analyzedWords.length;

  if (totalAnalyzed === 0) {
    return {
      totalWords: rawText.split(/\s+/).filter(Boolean).length,
      analyzedWords: 0,
      similarityScore: 0,
      similarityLevel: 'low',
      matchedPassages: [],
      excludedContent: {
        quotationsCount,
        quotationsExcluded: excludeQuotes,
        referencesExcluded,
        smallPhrasesExcluded: excludeSmallPhrases,
        minPhraseWords,
        wordsExcluded: excludedWordsCount,
        quotesFound: quotesFound.slice(0, 10)
      },
      coverage: 'Within-document cross-section passage comparison and open scholarly citation resolution. Commercial paywalled publisher indexes are excluded.',
      advisoryNotice: 'Document similarity indicates shared phrasing or internal repetition; it is NOT proof of plagiarism. Legitimate scientific writing routinely utilizes standardized methodologies, disciplinary terminology, and properly attributed citations.',
      disclaimer: 'Similarity does not equate to plagiarism.'
    };
  }

  // 4. Internal matched passages (recurring chunks across paragraphs)
  const paragraphs = workingText.split(/\n\s*\n/).map(p => p.trim()).filter(p => p.length > 30);
  const matchedPassages = [];
  let matchedWordCount = 0;

  // A. Paragraph-level identical duplicate blocks
  const seenParas = new Map();
  paragraphs.forEach((p, idx) => {
    const clean = p.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (seenParas.has(clean)) {
      const prev = seenParas.get(clean);
      const pWords = p.split(/\s+/).length;
      matchedWordCount += pWords;
      matchedPassages.push({
        id: `overlap-${idx}`,
        type: 'internal_passage_overlap',
        matchPercentage: 100,
        wordCount: pWords,
        sourceLocation: `Paragraph ${prev + 1}`,
        targetLocation: `Paragraph ${idx + 1}`,
        excerpt: p.length > 140 ? `${p.slice(0, 140)}...` : p,
        matchText: p,
        fullText: p,
        sourceLink: null,
        detail: `Verbatim passage overlap between Paragraph ${prev + 1} and Paragraph ${idx + 1}.`
      });
    } else {
      seenParas.set(clean, idx);
    }
  });

  // B. Repeated long key phrases (5-8 words) from findRepeatedPhrases
  const effectiveMinWords = excludeSmallPhrases ? Math.max(minPhraseWords, 8) : minPhraseWords;
  const repeated = findRepeatedPhrases(workingText, effectiveMinWords);
  repeated.forEach((r, idx) => {
    const pWordCount = r.phrase.split(/\s+/).length;
    matchedWordCount += pWordCount * (r.count - 1);
    matchedPassages.push({
      id: `repeat-${idx}`,
      type: 'repeated_key_phrase',
      matchPercentage: 100,
      wordCount: pWordCount,
      sourceLocation: 'Multiple locations in manuscript',
      targetLocation: `${r.count} occurrences`,
      excerpt: r.phrase,
      matchText: r.phrase,
      fullText: r.phrase,
      sourceLink: null,
      detail: `Recurring multi-word sequence appearing ${r.count} times within this document.`
    });
  });

  // C. Citation DOIs resolution for open source links
  const regex = /\b10\.\d{4,9}\/[-._;()/:A-Za-z0-9]+\b/g;
  const rawDois = rawText.match(regex) || [];
  const dois = [...new Set(rawDois.map(d => d.replace(/[,.;:)]$/, '')))];
  const citedSources = dois.slice(0, 10).map((doi, idx) => ({
    id: `doi-${idx}`,
    type: 'scholarly_citation_reference',
    matchPercentage: null,
    sourceLocation: 'In-text citation DOI',
    excerpt: `doi:${doi}`,
    matchText: doi,
    fullText: doi,
    sourceLink: `https://doi.org/${doi}`,
    detail: `Open-access Crossref scholarly source linked to DOI: ${doi}`
  }));

  // 5. Similarity score calculation
  const rawSimilarity = totalAnalyzed > 0 ? Math.round((Math.min(totalAnalyzed, matchedWordCount) / totalAnalyzed) * 100) : 0;
  const similarityScore = Math.min(100, Math.max(0, rawSimilarity));

  let similarityLevel = 'low';
  if (similarityScore > 25) similarityLevel = 'elevated';
  else if (similarityScore >= 12) similarityLevel = 'moderate';

  return {
    totalWords: rawText.split(/\s+/).filter(Boolean).length,
    analyzedWords: totalAnalyzed,
    similarityScore,
    similarityLevel,
    matchedPassages: [...matchedPassages.slice(0, 25), ...citedSources],
    excludedContent: {
      quotationsCount,
      quotationsExcluded: excludeQuotes,
      referencesExcluded: excludeReferences && referencesExcluded,
      smallPhrasesExcluded: excludeSmallPhrases,
      minPhraseWords: effectiveMinWords,
      wordsExcluded: excludedWordsCount,
      quotesFound: quotesFound.slice(0, 10)
    },
    coverage: 'Open-access scholarly DOI metadata, Crossref registry, and cross-section manuscript passage comparison. Proprietary subscription repositories are excluded.',
    advisoryNotice: 'Document similarity indicates shared phrasing or internal repetition; it is NOT proof of plagiarism. Legitimate scientific writing routinely utilizes standardized methodologies, disciplinary terminology, and properly attributed citations.',
    disclaimer: 'Similarity does not equate to plagiarism. Academic manuscripts require discipline-specific nomenclature, standard formulas, and contextual reference quotes.'
  };
}

export function findRepeatedPhrases(text, minWords = 5) {
  const normalized = text.toLowerCase().replace(/[^\p{L}\p{N}\s'-]/gu, ' ');
  const words = normalized.split(/\s+/).filter(Boolean);
  const found = new Map();
  const startN = Math.max(3, minWords);
  for (let n = startN; n <= 8; n++) {
    for (let i = 0; i <= words.length - n; i++) {
      const phraseWords = words.slice(i, i + n);
      if (phraseWords.every(w => STOP.has(w))) continue;
      const phrase = phraseWords.join(' ');
      found.set(phrase, (found.get(phrase) || 0) + 1);
    }
  }
  return [...found.entries()]
    .filter(([, count]) => count > 1)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 30)
    .map(([phrase, count]) => ({ phrase, count, note: 'Repeated within this document; not an internet or database similarity match.' }));
}

/**
 * Comprehensive Manuscript Originality & Similarity Assessment Engine
 */
export function assessOriginality(text) {
  const normalized = text.toLowerCase().replace(/[^\p{L}\p{N}\s'-]/gu, ' ');
  const words = normalized.split(/\s+/).filter(Boolean);
  const totalWords = words.length;

  if (totalWords === 0) {
    return {
      wordCount: 0,
      totalWords: 0,
      sentenceCount: 0,
      averageWordsPerSentence: 0,
      originalityScore: 100,
      originalityLevel: 'high',
      lexicalDiversity: 0,
      uniqueWordsCount: 0,
      guiraudIndex: 0,
      repeatedPhrases: [],
      duplicatePassages: [],
      formulaicPhrases: [],
      observations: [],
      scope: 'Within-document phrase repetition only',
      externalDatabaseChecked: false
    };
  }

  // 1. Lexical Diversity & Vocabulary Richness (Type-Token Ratio / TTR)
  const uniqueWords = new Set(words);
  const rawTtr = Math.round((uniqueWords.size / totalWords) * 100);
  const guiraud = totalWords > 10 ? Math.round((uniqueWords.size / Math.sqrt(totalWords)) * 10) / 10 : 0;

  // 2. Repeated Phrases (5 to 8 n-grams)
  const repeatedPhrases = findRepeatedPhrases(text);

  // 3. Duplicate / Near-Duplicate Paragraph Passages
  const rawParagraphs = text.split(/\n\s*\n/).map(p => p.trim()).filter(p => p.length > 50);
  const duplicatePassages = [];
  const seenParas = new Map();
  rawParagraphs.forEach((p, idx) => {
    const pClean = p.toLowerCase().replace(/[^a-z0-9]/g, '');
    if (seenParas.has(pClean)) {
      const prev = seenParas.get(pClean);
      duplicatePassages.push({
        count: 2,
        sourceLocation: `Section / Paragraph ${prev.idx + 1}`,
        targetLocation: `Section / Paragraph ${idx + 1}`,
        excerpt: p.length > 140 ? `${p.slice(0, 140)}...` : p,
        detail: `Verbatim passage duplication between Paragraph ${prev.idx + 1} and Paragraph ${idx + 1}.`,
        suggestedAction: 'Synthesize or cross-reference preceding discussion instead of repeating verbatim blocks.'
      });
    } else {
      seenParas.set(pClean, { idx });
    }
  });

  // 4. Academic Boilerplate & Formulaic Clichés Detection
  const CLICHES = [
    { pattern: /\bdue to the fact that\b/gi, replacement: 'because', reason: 'Wordy causal phrase' },
    { pattern: /\bit is important to note that\b/gi, replacement: 'notably', reason: 'Filler introductory formula' },
    { pattern: /\bin order to\b/gi, replacement: 'to', reason: 'Redundant infinitive marker' },
    { pattern: /\bat the end of the day\b/gi, replacement: 'ultimately / in conclusion', reason: 'Informal cliché' },
    { pattern: /\bplays a (?:vital|pivotal|crucial|key) role in\b/gi, replacement: 'is essential for / influences', reason: 'Overused academic cliché' },
    { pattern: /\ba large (?:number|amount) of\b/gi, replacement: 'many / numerous', reason: 'Imprecise quantifier' },
    { pattern: /\bthe vast majority of\b/gi, replacement: 'most', reason: 'Circumlocution' },
    { pattern: /\bin the present study\b/gi, replacement: 'here / in this study', reason: 'Verbose reference' },
    { pattern: /\bhas the potential to\b/gi, replacement: 'can / may', reason: 'Unnecessary hedging' },
    { pattern: /\bwith respect to\b/gi, replacement: 'regarding / for', reason: 'Padded prepositional phrase' },
    { pattern: /\bit goes without saying\b/gi, replacement: 'evidently / self-evidently', reason: 'Informal cliché' },
    { pattern: /\bcrystal clear\b/gi, replacement: 'transparent / unambiguous', reason: 'Informal idiom' },
    { pattern: /\bpave(?:s)? the way\b/gi, replacement: 'facilitates / enables', reason: 'Informal metaphor' }
  ];

  const formulaicPhrases = [];
  for (const c of CLICHES) {
    const matches = text.match(c.pattern);
    if (matches && matches.length > 0) {
      formulaicPhrases.push({
        phrase: matches[0].toLowerCase(),
        occurrences: matches.length,
        suggestedAlternative: c.replacement,
        suggestion: c.replacement,
        reason: c.reason
      });
    }
  }

  // 5. Score Calculation (100 base, deductions for duplication, heavy repetition, low TTR)
  let score = 96;
  if (duplicatePassages.length > 0) score -= Math.min(30, duplicatePassages.length * 15);
  if (repeatedPhrases.length > 5) score -= Math.min(20, (repeatedPhrases.length - 5) * 2);
  if (formulaicPhrases.length > 3) score -= Math.min(15, (formulaicPhrases.length - 3) * 2);
  if (rawTtr < 35 && totalWords > 100) score -= 12;
  else if (rawTtr < 45 && totalWords > 100) score -= 6;
  score = Math.max(25, Math.min(100, Math.round(score)));

  let originalityLevel = 'high';
  if (score < 65) originalityLevel = 'low';
  else if (score < 85) originalityLevel = 'moderate';

  // 6. Observations Summary for Researchers
  const sentences = text.split(/(?<=[.!?])\s+/).filter(Boolean);
  const sentenceCount = sentences.length || 1;
  const averageWordsPerSentence = Math.round((totalWords / sentenceCount) * 10) / 10;

  const observations = [];
  if (duplicatePassages.length > 0) {
    observations.push({
      level: 'warning',
      title: `${duplicatePassages.length} Duplicate Passage(s)`,
      detail: 'Verbatim internal duplication detected across distinct sections of the manuscript.'
    });
  }
  if (repeatedPhrases.length > 0) {
    observations.push({
      level: repeatedPhrases.length > 8 ? 'review' : 'info',
      title: `${repeatedPhrases.length} Repeated Key Phrase(s)`,
      detail: `${repeatedPhrases.length} long phrases (5–8 words) recur multiple times within the manuscript.`
    });
  }
  if (formulaicPhrases.length > 0) {
    observations.push({
      level: 'info',
      title: `${formulaicPhrases.length} Formulaic / Filler Phrase(s)`,
      detail: 'Common academic filler expressions detected that can be tightened for conciseness.'
    });
  }
  observations.push({
    level: rawTtr >= 50 ? 'info' : 'review',
    title: `Lexical Diversity (${rawTtr}%)`,
    detail: `Unique vocabulary comprises ${uniqueWords.size} unique words out of ${totalWords} total words (Guiraud index: ${guiraud}).`
  });

  return {
    wordCount: totalWords,
    totalWords,
    sentenceCount,
    averageWordsPerSentence,
    originalityScore: score,
    originalityLevel,
    lexicalDiversity: rawTtr,
    uniqueWordsCount: uniqueWords.size,
    guiraudIndex: guiraud,
    duplicatePassages,
    repeatedPhrases,
    formulaicPhrases,
    observations,
    scope: 'Within-document phrase repetition only',
    externalDatabaseChecked: false
  };
}

/**
 * Extracts DOI strings from arbitrary text
 */
function extractDOIs(text) {
  const regex = /\b10\.\d{4,9}\/[-._;()/:A-Za-z0-9]+\b/g;
  const matches = text.match(regex) || [];
  return [...new Set(matches.map(d => d.replace(/[,.;:)]$/, '')))];
}

/**
 * Fetches DOI metadata from public Crossref API with a timeout
 */
async function fetchCrossrefMetadata(doi) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 4000);
  try {
    const url = `https://api.crossref.org/works/${encodeURIComponent(doi)}`;
    const res = await fetch(url, {
      headers: {
        'User-Agent': 'ResearchProof-AI/1.0 (mailto:support@researchproof.org)'
      },
      signal: controller.signal
    });
    if (!res.ok) {
      return { doi, verified: false, status: res.status === 404 ? 'Not found in Crossref' : `HTTP ${res.status}` };
    }
    const data = await res.json();
    const message = data.message || {};
    const authors = (message.author || []).map(a => `${a.family || ''} ${a.given || ''}`.trim()).filter(Boolean);
    const publishedYear = message['published-print']?.['date-parts']?.[0]?.[0] ||
                          message['published-online']?.['date-parts']?.[0]?.[0] ||
                          message['issued']?.['date-parts']?.[0]?.[0] || null;
    const title = Array.isArray(message.title) ? message.title[0] : (message.title || '');
    const container = Array.isArray(message['container-title']) ? message['container-title'][0] : '';

    return {
      doi,
      verified: true,
      title,
      authors: authors.slice(0, 4),
      year: publishedYear,
      journal: container,
      verifiedAt: new Date().toISOString()
    };
  } catch (err) {
    return { doi, verified: false, status: err.name === 'AbortError' ? 'Lookup timed out' : 'Service unavailable' };
  } finally {
    clearTimeout(timeoutId);
  }
}

export async function checkCitations(text) {
  const citations = [...text.matchAll(/\(([^()]{1,120}?(?:19|20)\d{2}[a-z]?[^()]*)\)/g)].map(m => m[1].trim());
  const refHeading = /references|bibliography|works cited/i.exec(text);
  const referenceSection = refHeading ? text.slice(refHeading.index + refHeading[0].length) : '';
  const referenceLines = referenceSection.split(/\n/).map(s => s.trim()).filter(Boolean);
  const issues = [];
  
  if (citations.length && !refHeading) {
    issues.push({ level: 'warning', detail: 'In-text citation-like patterns were found, but no References/Bibliography heading was detected.' });
  }
  if (refHeading && !referenceLines.length) {
    issues.push({ level: 'warning', detail: 'A references heading was found, but no reference entries were detected after it.' });
  }
  if (!citations.length) {
    issues.push({ level: 'info', detail: 'No parenthetical author-year citations were detected by this basic checker. Other citation styles may not be recognised.' });
  }
  if (referenceLines.some(line => !/\b(19|20)\d{2}\b/.test(line))) {
    issues.push({ level: 'review', detail: 'One or more reference lines may be missing a four-digit publication year. Check manually.' });
  }

  // Crossref DOI Verification (Architecture Section 9)
  const detectedDOIs = extractDOIs(text);
  const doiVerifications = [];
  if (detectedDOIs.length > 0) {
    // Check up to 5 DOIs per run to keep latency low
    const targetDOIs = detectedDOIs.slice(0, 5);
    const lookups = await Promise.all(targetDOIs.map(doi => fetchCrossrefMetadata(doi)));
    for (const res of lookups) {
      doiVerifications.push(res);
      if (!res.verified) {
        issues.push({
          level: 'warning',
          detail: `DOI ${res.doi} could not be confirmed via Crossref (${res.status || 'Unresolved'}). Verify citation manually.`
        });
      }
    }
  }

  return {
    detectedAuthorYearCitations: citations,
    referenceEntryCount: referenceLines.length,
    detectedDOIs,
    doiVerifications,
    issues,
    limitation: 'Crossref verification confirms DOI metadata existence only; it does not confirm whether the cited source supports your scientific claim.'
  };
}

export async function humanizeWithReverseGPT({ text, apiKey }) {
  const key = apiKey || process.env.REVERSEGPT_API_KEY;
  if (!key) {
    const error = new Error('ReverseGPT API key is missing. Set REVERSEGPT_API_KEY in server/.env.');
    error.status = 503;
    throw error;
  }

  // 1. Submit humanize job
  const initRes = await fetch('https://www.reversegpt.ai/api/v1/humanize', {
    method: 'POST',
    headers: {
      'Authorization': `Bearer ${key}`,
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      text,
      ultra: false
    })
  });

  if (!initRes.ok) {
    const errText = await initRes.text().catch(() => '');
    const error = new Error(`ReverseGPT job initialization failed (${initRes.status}): ${errText.slice(0, 300)}`);
    error.status = initRes.status;
    throw error;
  }

  const envelope = await initRes.json();
  const pollUrl = envelope?.job?.url || (envelope?.job?.id ? `https://www.reversegpt.ai/api/v1/jobs/${envelope.job.id}` : null);
  
  if (!pollUrl) {
    throw new Error('ReverseGPT did not return a valid job status URL.');
  }

  // If already finished on 200
  if (envelope?.job?.status === 'completed' && envelope?.result?.humanizedText) {
    return {
      revisedText: envelope.result.humanizedText,
      changeSummary: 'Revision completed via ReverseGPT pipeline.',
      cautions: ['ReverseGPT transformation applied. Verify academic integrity and claims.']
    };
  }

  // 2. Poll until completed (timeout after 60s)
  const maxAttempts = 30;
  for (let attempt = 0; attempt < maxAttempts; attempt++) {
    await new Promise(r => setTimeout(r, 2000));
    const checkRes = await fetch(pollUrl, {
      headers: {
        'Authorization': `Bearer ${key}`
      }
    });

    if (checkRes.ok) {
      const pollData = await checkRes.json();
      if (pollData?.job?.status === 'completed' && pollData?.result?.humanizedText) {
        return {
          revisedText: pollData.result.humanizedText,
          changeSummary: 'Revision completed via ReverseGPT humanization pipeline.',
          cautions: ['ReverseGPT transformation applied. Verify scholarly terminology, citations, and claims.']
        };
      }
      if (pollData?.job?.status === 'failed') {
        throw new Error(`ReverseGPT processing failed: ${pollData?.error?.message || 'Unknown processing error'}`);
      }
    }
  }

  throw new Error('ReverseGPT job timed out after 60 seconds.');
}

